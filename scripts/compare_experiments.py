"""Compare two ``results/experiments`` trees row by row.

Written for the capture-rule re-derivation: every stage-5 CSV is regenerated by
corrected code and the question is how far, and in which direction, each
published quantity moved. The script is generic, though: it pairs every CSV in
``--new`` with the file of the same name in ``--old``, aligns rows on the
experiment keys (seed, class_name, alpha, rho, method) when those columns exist
and positionally otherwise, and reports the differences per (file, rho).

Two expectations are checked and, with ``--strict``, enforced with a non-zero
exit so a driver can stop before deriving tables from a run that contradicts
the theory of the fix:

* rho = 0.5 rows must be bit-identical in region_fnr, lam_index and
  marked_area_fraction. 0.5 is exactly representable in float16, so the
  capture rule never changes there; any difference is a separate defect.
* lam_index must never increase. The fix lowers the calibration loss curve
  pointwise, so the selected threshold can only stay or move to a smaller
  index. The realized test FNR, by contrast, may move either way: a smaller
  threshold marks less and can miss more on the test side. That is why the
  FNR direction is reported, not asserted.

Usage:
    python scripts/compare_experiments.py \
        --old results/experiments_pre_p1 --new results/experiments \
        --out results/p1_rerun_diff.csv --strict
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

KEYS = ["seed", "class_name", "alpha", "rho", "method"]
TRACKED = ["region_fnr", "lam_index", "marked_area_fraction"]


def _align(new: pd.DataFrame, old: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, str]:
    """Return the two frames aligned row-for-row and how the alignment was made."""
    if all(k in new.columns for k in KEYS) and all(k in old.columns for k in KEYS):
        n = new.sort_values(KEYS, kind="stable").reset_index(drop=True)
        o = old.sort_values(KEYS, kind="stable").reset_index(drop=True)
        if len(n) == len(o) and all(
            (n[k].astype(str).to_numpy() == o[k].astype(str).to_numpy()).all() for k in KEYS
        ):
            return n, o, "keys"
        merged = n.merge(o, on=KEYS, how="inner", suffixes=("", "__old"))
        o2 = merged[[c for c in merged.columns if c.endswith("__old")]].copy()
        o2.columns = [c[: -len("__old")] for c in o2.columns]
        for k in KEYS:
            o2[k] = merged[k]
        n2 = merged[[c for c in merged.columns if not c.endswith("__old")]]
        return n2.reset_index(drop=True), o2.reset_index(drop=True), "merge"
    if len(new) == len(old):
        return new.reset_index(drop=True), old.reset_index(drop=True), "positional"
    raise ValueError(f"cannot align: {len(new)} new rows vs {len(old)} old rows, no key columns")


def compare_file(name: str, new: pd.DataFrame, old: pd.DataFrame) -> tuple[list[dict], list[str]]:
    rows: list[dict] = []
    violations: list[str] = []
    n, o, how = _align(new, old)
    if len(n) == 0:
        violations.append(f"{name}: no rows could be aligned")
        return rows, violations

    shared_numeric = [
        c for c in n.columns
        if c in o.columns and c not in KEYS and pd.api.types.is_numeric_dtype(n[c])
        and pd.api.types.is_numeric_dtype(o[c])
    ]
    groups = [(None, np.ones(len(n), dtype=bool))]
    if "rho" in n.columns:
        groups = [(r, np.isclose(n["rho"].to_numpy(dtype=float), r))
                  for r in sorted(n["rho"].dropna().unique())]

    for rho, m in groups:
        if not m.any():
            continue
        rec: dict = {"file": name, "rho": rho, "n_rows": int(m.sum()), "align": how,
                     "n_aligned_of_new": f"{len(n)}/{len(new)}"}
        for col in TRACKED:
            if col in shared_numeric:
                d = n.loc[m, col].to_numpy(dtype=float) - o.loc[m, col].to_numpy(dtype=float)
                d = np.where(np.isnan(d), 0.0, d)  # NaN in both sides counts as unchanged
                rec[f"max_abs_d_{col}"] = float(np.abs(d).max()) if d.size else 0.0
                rec[f"mean_d_{col}"] = float(d.mean()) if d.size else 0.0
                rec[f"n_down_{col}"] = int((d < 0).sum())
                rec[f"n_up_{col}"] = int((d > 0).sum())
            else:
                rec[f"max_abs_d_{col}"] = np.nan
        other = [c for c in shared_numeric if c not in TRACKED]
        changed_other = []
        for c in other:
            a = n.loc[m, c].to_numpy(dtype=float)
            b = o.loc[m, c].to_numpy(dtype=float)
            diff = ~((a == b) | (np.isnan(a) & np.isnan(b)))
            if diff.any():
                changed_other.append(c)
        rec["other_changed_columns"] = ";".join(changed_other)
        rows.append(rec)

        # Expectations.
        if rho is not None and np.isclose(rho, 0.5):
            for col in TRACKED:
                if rec.get(f"max_abs_d_{col}", 0.0) and rec[f"max_abs_d_{col}"] > 0:
                    violations.append(
                        f"{name} rho=0.5: {col} changed (max |d| = {rec[f'max_abs_d_{col}']:.6g})"
                    )
        if "lam_index" in shared_numeric and rec.get("n_up_lam_index", 0) > 0:
            violations.append(
                f"{name} rho={rho}: lam_index increased in {rec['n_up_lam_index']} rows"
            )
    return rows, violations


SIDECAR_SKIP = {"completed_utc", "git_revision", "n_records", "timestamp"}


def _flatten(d: dict, prefix: str = "") -> dict:
    out: dict = {}
    for k, v in d.items():
        if k in SIDECAR_SKIP:
            continue
        if isinstance(v, dict):
            out.update(_flatten(v, prefix + k + "."))
        else:
            out[prefix + k] = v
    return out


def compare_sidecars(old_dir: Path, new_dir: Path, names: list[str]) -> list[tuple[str, dict]]:
    """Return (csv name, {field: (old, new)}) for every pair whose recorded
    arguments differ, ignoring fields the old sidecar left unset."""
    import json

    diffs: list[tuple[str, dict]] = []
    for name in names:
        stem = name[:-4]
        # Companion files (…_triage.csv) share the main run's sidecar.
        for cand in (stem, stem.rsplit("_", 1)[0]):
            po, pn = old_dir / f"{cand}.meta.json", new_dir / f"{cand}.meta.json"
            if po.exists() and pn.exists():
                break
        else:
            continue
        try:
            fo = _flatten(json.load(open(po)))
            fn = _flatten(json.load(open(pn)))
        except Exception:  # noqa: BLE001
            continue
        d = {k: (fo[k], fn.get(k)) for k in fo if fo[k] is not None and fo[k] != fn.get(k)}
        if d:
            diffs.append((name, {k: (str(a)[:60], str(b)[:60]) for k, (a, b) in d.items()}))
    return diffs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--old", default="results/experiments_pre_p1")
    ap.add_argument("--new", default="results/experiments")
    ap.add_argument("--out", default="results/p1_rerun_diff.csv")
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 if rho=0.5 moved or lam_index rose anywhere")
    ap.add_argument("--top", type=int, default=40, help="rows to print, largest FNR move first")
    args = ap.parse_args()

    old_dir, new_dir = Path(args.old), Path(args.new)
    old_files = {p.name for p in old_dir.glob("*.csv")}
    new_files = {p.name for p in new_dir.glob("*.csv")}
    only_old = sorted(old_files - new_files)
    only_new = sorted(new_files - old_files)

    rows: list[dict] = []
    violations: list[str] = []
    unreadable: list[str] = []
    for name in sorted(old_files & new_files):
        try:
            new = pd.read_csv(new_dir / name)
            old = pd.read_csv(old_dir / name)
            r, v = compare_file(name, new, old)
        except Exception as exc:  # noqa: BLE001 - report and continue
            # A file that cannot be compared is not "no difference"; it is a
            # gap in the evidence, so under --strict it counts as a violation.
            unreadable.append(f"{name}: {exc}")
            violations.append(f"{name}: not comparable ({exc})")
            continue
        rows.extend(r)
        violations.extend(v)

    # Sidecar arguments. Two files with the same name can come from different
    # invocations; the 2026-09-07 re-run produced x7 files with one seed where
    # the published run had 25, and only the sidecar's `seeds` field showed it.
    # Fields the old sidecar did not record (schema growth) are not differences.
    arg_diffs = compare_sidecars(old_dir, new_dir, sorted(old_files & new_files))
    for name, d in arg_diffs:
        violations.append(f"{name}: run arguments differ from the old sidecar: {d}")

    report = pd.DataFrame(rows)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    report.to_csv(args.out, index=False)

    print(f"compared {len(old_files & new_files)} files  ({len(only_old)} only in old, "
          f"{len(only_new)} only in new, {len(unreadable)} unreadable)")
    if only_old:
        print("  NOT REPRODUCED (only in old):")
        for f in only_old:
            print("   ", f)
    if only_new:
        print("  NEW (only in new):", ", ".join(only_new))
    for u in unreadable:
        print("  UNREADABLE:", u)

    if not report.empty and "max_abs_d_region_fnr" in report.columns:
        moved = report[
            (report["max_abs_d_region_fnr"].fillna(0) > 0)
            | (report.get("max_abs_d_lam_index", pd.Series(0, index=report.index)).fillna(0) > 0)
            | (report.get("max_abs_d_marked_area_fraction", pd.Series(0, index=report.index)).fillna(0) > 0)
        ].copy()
        unchanged = len(report) - len(moved)
        print(f"\n{len(moved)} (file, rho) pairs moved, {unchanged} unchanged")
        for r in (0.1, 0.5):
            sub = moved[np.isclose(moved["rho"].astype(float), r)] if "rho" in moved else moved.iloc[0:0]
            print(f"  rho={r}: {len(sub)} pairs moved")
        moved = moved.sort_values("max_abs_d_region_fnr", ascending=False)
        print("\n  file                                                    rho  n     max|dFNR|  mean dFNR  "
              "FNR-  FNR+  lam-  lam+  max|dArea|")
        for _, x in moved.head(args.top).iterrows():
            print("  %-56s %.1f %5d  %.6f  %+.6f  %4d  %4d  %4d  %4d  %.6f" % (
                x["file"][:56], float(x["rho"]), int(x["n_rows"]),
                x.get("max_abs_d_region_fnr", 0.0) or 0.0, x.get("mean_d_region_fnr", 0.0) or 0.0,
                x.get("n_down_region_fnr", 0) or 0, x.get("n_up_region_fnr", 0) or 0,
                x.get("n_down_lam_index", 0) or 0, x.get("n_up_lam_index", 0) or 0,
                x.get("max_abs_d_marked_area_fraction", 0.0) or 0.0))
        other = report[report["other_changed_columns"].fillna("") != ""]
        if len(other):
            print(f"\n{len(other)} (file, rho) pairs changed in columns outside the tracked three:")
            for _, x in other.head(args.top).iterrows():
                print(f"  {x['file']}  rho={x['rho']}  -> {x['other_changed_columns']}")

    print(f"\nreport written to {args.out}")
    if violations:
        print(f"\nEXPECTATIONS VIOLATED ({len(violations)}):")
        for v in violations:
            print("  ", v)
        return 1 if args.strict else 0
    print("\nexpectations hold: rho=0.5 unchanged, lam_index never rose")
    return 0


if __name__ == "__main__":
    sys.exit(main())
